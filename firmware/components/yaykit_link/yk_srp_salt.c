esp_err_t yk_srp_verifier(const char *user, const char *pass, const uint8_t salt[YK_SRP_SALT_LEN], char **verifier,
                          int *verifier_len) {
    // x = H(s | H(I ":" P)), v = g^x mod N, as esp_srp computes them (calculate_x, _esp_srp_gen_salt_verifier).
    uint8_t inner[64], x_bytes[64];
    mbedtls_sha512_context h;
    mbedtls_sha512_init(&h);
    mbedtls_sha512_starts(&h, 0);
    mbedtls_sha512_update(&h, (const unsigned char *)user, strlen(user));
    mbedtls_sha512_update(&h, (const unsigned char *)":", 1);
    mbedtls_sha512_update(&h, (const unsigned char *)pass, strlen(pass));
    mbedtls_sha512_finish(&h, inner);
    mbedtls_sha512_starts(&h, 0);
    mbedtls_sha512_update(&h, salt, YK_SRP_SALT_LEN);
    mbedtls_sha512_update(&h, inner, sizeof(inner));
    mbedtls_sha512_finish(&h, x_bytes);
    mbedtls_sha512_free(&h);
    mbedtls_mpi n, g, x, v;
    mbedtls_mpi_init(&n), mbedtls_mpi_init(&g), mbedtls_mpi_init(&x), mbedtls_mpi_init(&v);
    int ret = mbedtls_mpi_read_binary(&n, N_3072, sizeof(N_3072));
    if (!ret) ret = mbedtls_mpi_lset(&g, 5);
    if (!ret) ret = mbedtls_mpi_read_binary(&x, x_bytes, sizeof(x_bytes));
    if (!ret) ret = mbedtls_mpi_exp_mod(&v, &g, &x, &n, NULL);
    esp_err_t err = ret ? ESP_FAIL : ESP_OK;
    if (err == ESP_OK) {
        *verifier_len = (int)mbedtls_mpi_size(&v);
        *verifier = malloc((size_t)*verifier_len);
        if (!*verifier || mbedtls_mpi_write_binary(&v, (unsigned char *)*verifier, (size_t)*verifier_len)) {
            free(*verifier);
            *verifier = NULL;
            err = ESP_ERR_NO_MEM;
        }
    }
    mbedtls_mpi_free(&n), mbedtls_mpi_free(&g), mbedtls_mpi_free(&x), mbedtls_mpi_free(&v);
    memset(inner, 0, sizeof(inner));
    memset(x_bytes, 0, sizeof(x_bytes));
    return err;
}

esp_err_t yk_srp_salt_verifier(const char *user, const char *pass, uint8_t salt[YK_SRP_SALT_LEN], char **verifier,
                               int *verifier_len) {
    // Never a 0 first byte. esp_srp_gen_salt_verifier() writes its random salt at its own length, so such a salt comes
    // out a byte short while its caller and the phone take 16 (and the phone's library drops leading zeros too): no
    // phone could pair in that session, 1 time in 256 (found 2026-10-19 with the Android app).
    do esp_fill_random(salt, YK_SRP_SALT_LEN);
    while (salt[0] == 0);
    return yk_srp_verifier(user, pass, salt, verifier, verifier_len);
}
